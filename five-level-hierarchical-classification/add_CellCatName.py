def add_cell_category_column(data_frame):
    """
    Add a 'CellCatName' column to the DataFrame based on 'MemCatName' and 'NucCatName'
    
    Parameters:
    data_frame (pandas.DataFrame): DataFrame containing 'MemCatName' and 'NucCatName' columns
    
    Returns:
    pandas.DataFrame: DataFrame with added 'CellCatName' column
    """
    # Create a new column by applying the assign_cell_category function
    data_frame['CellCatName'] = data_frame.apply(
        lambda row: assign_cell_category(row['MemCatName'], row['NucCatName']), 
        axis=1
    )
    
    return data_frame


